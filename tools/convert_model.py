"""Turns art/maiden.bbmodel into the mod's model geometry and skins.

Writes:
  src/main/java/net/maidens/client/MaidenGeometry.java   (the parts, as Minecraft model code)
  src/main/resources/assets/maidens/textures/entity/maiden/maiden_<n>.png   (one per skin in the file)
  src/main/resources/assets/maidens/textures/entity/maiden/casual_1.png    (the casual one, "...comp")

Blockbench (y up, feet at 0, the model's right at +x) becomes Minecraft model space (y down, feet at 24,
the model's right at -x): x -> -x, y -> 24 - y, z stays; rotations about x and y change sign.
The six groups become HumanoidModel's parts (head, body, right_arm, left_arm, right_leg, left_leg; hat is empty),
so the vanilla walk, head-look and item-holding code drives them. A rotated cube becomes a child part.
"""
import base64, json, math, os, sys

# usage: convert_model.py [model.bbmodel ClassName]   (default: art/maiden.bbmodel -> MaidenGeometry, the skins)
#        convert_model.py art/maiden_casual.bbmodel MaidenCasualGeometry   (her body at home; writes casual_1.png)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'art', 'maiden.bbmodel')
CLASS = sys.argv[2] if len(sys.argv) > 2 else 'MaidenGeometry'
J = json.load(open(SRC))
OUT = os.path.join(ROOT, 'src', 'main', 'java', 'net', 'maidens', 'client', CLASS + '.java')
TEX = os.path.join(ROOT, 'src', 'main', 'resources', 'assets', 'maidens', 'textures', 'entity', 'maiden')

def f(v):
    s = f'{v:.5f}'.rstrip('0').rstrip('.')
    return (s if s not in ('-0', '') else '0') + 'F'

def mc(p):  # Blockbench point -> model space
    return (-p[0], 24 - p[1], p[2])

groups = {g['uuid']: g for g in J['groups']}
elements = {e['uuid']: e for e in J['elements']}
lines, poses = [], {}
for node in J['outliner']:
    g = groups[node['uuid']]; name = g['name']
    gp = mc(g['origin'])
    poses[name] = gp
    var = 'p_' + name
    cubes, kids = [], []
    for cu in node['children']:
        e = elements[cu]
        fr, to = e['from'], e['to']
        w, h, d = (to[i] - fr[i] for i in range(3))
        uv = e.get('uv_offset') or [int(min(e['faces']['east']['uv'][0], e['faces']['east']['uv'][2])),
                                    int(min(e['faces']['up']['uv'][1], e['faces']['up']['uv'][3]))]
        inf = e.get('inflate', 0) or 0
        rot = e.get('rotation') or [0, 0, 0]
        lo = mc([to[0], to[1], fr[2]])                     # the box's minimum corner in model space
        # rotated cubes, and her chest piece (hidden on men and children), are parts of their own
        if any(abs(r) > 1e-9 for r in rot) or e['name'] == 'breast':
            ep = mc(e.get('origin') or g['origin'])
            rel_pivot = tuple(ep[i] - gp[i] for i in range(3))
            box = tuple(lo[i] - ep[i] for i in range(3))
            kids.append((e['name'], uv, box, (w, h, d), inf, rel_pivot, (-rot[0], -rot[1], rot[2])))
        else:
            box = tuple(lo[i] - gp[i] for i in range(3))
            cubes.append((e['name'], uv, box, (w, h, d), inf))
    cb = 'CubeListBuilder.create()'
    for n, uv, box, size, inf in cubes:
        cb += (f'\n                // {n}\n                .texOffs({uv[0]}, {uv[1]}).addBox({f(box[0])}, {f(box[1])}, {f(box[2])}, '
               f'{f(size[0])}, {f(size[1])}, {f(size[2])}, new CubeDeformation({f(inf)}))')
    lines.append(f'        PartDefinition {var} = root.addOrReplaceChild("{name}", {cb},\n'
                 f'                PartPose.offset({f(gp[0])}, {f(gp[1])}, {f(gp[2])}));')
    for n, uv, box, size, inf, piv, r in kids:
        rr = [math.radians(x) for x in r]
        lines.append(f'        {var}.addOrReplaceChild("{n}_cube", CubeListBuilder.create()\n'
                     f'                .texOffs({uv[0]}, {uv[1]}).addBox({f(box[0])}, {f(box[1])}, {f(box[2])}, '
                     f'{f(size[0])}, {f(size[1])}, {f(size[2])}, new CubeDeformation({f(inf)}))'
                     f',\n                PartPose.offsetAndRotation({f(piv[0])}, {f(piv[1])}, {f(piv[2])}, '
                     f'{f(rr[0])}, {f(rr[1])}, {f(rr[2])}));')
pose_consts = '\n'.join(f'    static final float[] {n.upper()} = {{{f(p[0])}, {f(p[1])}, {f(p[2])}}};' for n, p in poses.items())
java = f'''package net.maidens.client;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

/** Generated by tools/convert_model.py from {os.path.relpath(SRC, ROOT)}. Don't edit by hand: change the .bbmodel and rerun. */
public final class {CLASS} {{
    private {CLASS}() {{}}

    /** Each part's pivot in model space (where HumanoidModel's own positions get put back after it moves them). */
{pose_consts}

    public static LayerDefinition create() {{
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
{chr(10).join(lines)}
        root.addOrReplaceChild("hat", CubeListBuilder.create(), PartPose.offset({f(poses['head'][0])}, {f(poses['head'][1])}, {f(poses['head'][2])}));
        return LayerDefinition.create(mesh, {J['resolution']['width']}, {J['resolution']['height']});
    }}
}}
'''
os.makedirs(os.path.dirname(OUT), exist_ok=True); open(OUT, 'w').write(java)
os.makedirs(TEX, exist_ok=True)
# skins: altplayer_skin.png is maiden_1, altplayer_skin_<n>.png maiden_<n>; the "comp" one is her casual clothes
# (casual_1.png; tools/make_casual.py makes the others from it)
import re
count = 0
casual = CLASS != 'MaidenGeometry'
for t in J['textures']:
    data = base64.b64decode(t['source'].split(',', 1)[1])
    name = t['name']
    if 'comp' in name or casual:
        continue            # the casual body's clothes come from tools/make_layers.py
    else:
        m = re.search(r'_(\d+)\.png$', name)
        out = f'maiden_{m.group(1) if m else 1}.png'
    open(os.path.join(TEX, out), 'wb').write(data)
    count += 1
print('model +', count, 'textures')
